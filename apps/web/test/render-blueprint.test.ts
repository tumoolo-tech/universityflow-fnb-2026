import { existsSync, readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';

/**
 * render.yaml, the Render Blueprint (docs/deploy/README.md). Render is for the STAGING site only:
 * it has no South African region, so student data never goes there (the locked hosting decision).
 * These tests keep the file honest: synthetic data only, no secret in the repository, every
 * variable documented, and a health check that exists.
 */

interface EnvVar {
  key: string;
  value?: string | number | boolean;
  sync?: boolean;
  generateValue?: boolean;
}
interface Service {
  type: string;
  name: string;
  runtime: string;
  region?: string;
  plan?: string;
  buildCommand?: string;
  startCommand?: string;
  healthCheckPath?: string;
  envVars?: EnvVar[];
}

const root = new URL('../../../', import.meta.url);
const blueprint = parse(readFileSync(new URL('render.yaml', root), 'utf8')) as {
  services: Service[];
  databases?: unknown[];
};
const example = readFileSync(new URL('.env.example', root), 'utf8');
const documented = new Set(
  [...example.matchAll(/^\s*#?\s*([A-Z][A-Z0-9_]*)=/gm)].map((m) => m[1] as string),
);

/** Values that are fine in a public file: switches, never credentials. */
const PLAIN_VALUES: Record<string, string> = {
  UF_DEPLOYMENT: 'staging',
  UF_PROVIDERS: 'local',
  UF_CATALOGUE_PREVIEW: '1',
};

describe('render.yaml (the staging Blueprint)', () => {
  const services = blueprint.services;

  it('has one web service and no Render database: no student data on Render', () => {
    expect(services).toHaveLength(1);
    expect(services[0]?.type).toBe('web');
    expect(services[0]?.runtime).toBe('node');
    expect(blueprint.databases ?? []).toEqual([]);
  });

  it('is staging, on the stand-ins, so it can never be production', () => {
    const env = new Map(services[0]?.envVars?.map((v) => [v.key, v]));
    expect(env.get('UF_DEPLOYMENT')?.value).toBe('staging');
    expect(env.get('UF_PROVIDERS')?.value).toBe('local');
    // No real database, bucket, SMS provider, job scheduler or AI key: the stand-ins only.
    // The same list readConfig refuses on staging (A5-11).
    for (const name of [
      'DATABASE_URL',
      'ANTHROPIC_API_KEY',
      'ELEVENLABS_API_KEY',
      'EXPO_ACCESS_TOKEN',
      'UF_MESSAGING_WEBHOOK_SECRET',
      'UF_SMS_PROVIDER',
      'UF_JOBS_PROVIDER',
      'UF_WHATSAPP_PROVIDER',
      'UF_PUSH_PROVIDER',
      'UF_REVIEW_PHONE',
      'UF_REVIEW_PIN_HASH',
      'UF_REVIEW_UNTIL',
      'AWS_ACCESS_KEY_ID',
      'AWS_SECRET_ACCESS_KEY',
      'AWS_SESSION_TOKEN',
    ]) {
      expect(env.has(name), name).toBe(false);
    }
    expect([...env.keys()].filter((name) => name.startsWith('UF_S3_'))).toEqual([]);
  });

  it('names only variables .env.example documents', () => {
    for (const variable of services.flatMap((s) => s.envVars ?? [])) {
      expect(documented.has(variable.key), variable.key).toBe(true);
    }
  });

  it('holds no secret: a value only for a plain switch; others generated by Render or set by hand', () => {
    for (const variable of services.flatMap((s) => s.envVars ?? [])) {
      if (variable.value !== undefined) {
        expect(PLAIN_VALUES[variable.key], `${variable.key} has a value in render.yaml`).toBe(
          String(variable.value),
        );
      } else {
        expect(variable.sync === false || variable.generateValue === true, variable.key).toBe(true);
      }
    }
    // AUTH_SECRET is generated by Render, never written here.
    const secret = services[0]?.envVars?.find((v) => v.key === 'AUTH_SECRET');
    expect(secret).toEqual({ key: 'AUTH_SECRET', generateValue: true });
    // A5-10: the access gate's password is typed in the dashboard, never written here.
    const gate = services[0]?.envVars?.find((v) => v.key === 'UF_STAGING_PASSWORD');
    expect(gate).toEqual({ key: 'UF_STAGING_PASSWORD', sync: false });
  });

  it('checks a health path that the app serves', () => {
    const path = services[0]?.healthCheckPath ?? '';
    expect(path).toBe('/api/health');
    expect(existsSync(new URL(`apps/web/app${path}/route.ts`, root))).toBe(true);
  });

  it('builds and starts the web app from the monorepo, bound to Render’s port', () => {
    expect(services[0]?.buildCommand).toMatch(/pnpm install --frozen-lockfile/);
    expect(services[0]?.buildCommand).toMatch(/--filter @universityflow\/web build/);
    expect(services[0]?.startCommand).toMatch(/next start/);
    expect(services[0]?.startCommand).toMatch(/--port \$PORT/);
  });
});
