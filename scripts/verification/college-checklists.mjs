/**
 * The public TVET colleges' verification checklists (planning.md §19.1): one file per province,
 * and one for the national teach-outs. Pure: `collegeChecklists` takes the loaded records and the
 * data files' text and returns `{ fileName: markdown }`; checklists.mjs renders the rest.
 *
 * Every college has two records a person checks against two different sources: the **register
 * record** against DHET's own list (`college:<id>`), and the **site record** against the college's
 * own website (`college-site:<id>`). Each programme is checked against its page and its entry
 * quote against the page that prints it (`college-programme:<id>`). A value the college doesn't
 * print reads "not published", never a default (gotcha 40).
 */

const UNCHECKED = '☐';
const NOT_PUBLISHED = 'not published';
const HEADER =
  '| Field | Value in the data | Source says (only if different) | ✓ |\n|---|---|---|---|';

function cell(value) {
  if (value === null || value === undefined) return '_(none)_';
  const text = String(value);
  if (text.trim() === '') return '_(empty)_';
  return text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}
const row = (field, value) => `| ${cell(field)} | ${cell(value)} |  | ${UNCHECKED} |`;
const status = (r) =>
  r.verifiedOn && r.verifiedBy
    ? `Verified on ${r.verifiedOn} by ${r.verifiedBy}`
    : 'DRAFT (no verifiedOn / verifiedBy)';
const provenance = (r) => [
  row('sourceUrl (opens?)', r.sourceUrl),
  row('academicYear', r.academicYear),
  `| Status | ${cell(status(r))} | — | — |`,
];
const footer = (key) =>
  [
    row(
      'Whole record matches the source',
      'Then add `verifiedOn` and `verifiedBy` ([how](README.md#how-to-record-a-verification-the-exact-edit))',
    ),
    '',
    `<!-- record:${key} -->`,
    '',
  ].join('\n');

/** Every record key the colleges add (checklists.mjs `allRecordKeys`). */
export function collegeRecordKeys(raw) {
  return [
    ...(raw.colleges ?? []).flatMap((c) => [
      `college:${c.id}`,
      ...(c.site ? [`college-site:${c.id}`] : []),
    ]),
    ...(raw.collegeProgrammes ?? []).map((p) => `college-programme:${p.id}`),
    ...(raw.teachOutNotices ?? []).map((n) => `teach-out:${n.id}`),
  ];
}

/** `path:line` of the first line holding `needle` in any college data file. */
function where(sources, needle) {
  for (const [key, source] of Object.entries(sources)) {
    if (!key.startsWith('colleges-')) continue;
    const index = source.lines.findIndex((line) => line.includes(needle));
    if (index !== -1) return `\`${source.path}:${index + 1}\``;
  }
  return '_(not found in the data files)_';
}

const provinceFile = (province) => `colleges-${province.toLowerCase().replace(/[^a-z]+/g, '-')}.md`;

function preamble(title, intro, count) {
  return [
    `# ${title}: verification checklist`,
    '',
    '<!-- GENERATED by `pnpm verification:checklists` from packages/catalogue. Edit the data, then regenerate. -->',
    '',
    '> Generated from the catalogue: every value below is what the data holds today, not what the',
    '> source says. Open each source, compare, and mark the last column **☑** (matches) or **☒**',
    '> (differs: write what the source says in the third column, and add it to',
    '> [proposed-corrections.md](proposed-corrections.md)). A tick survives `pnpm verification:checklists`',
    '> only while its row is unchanged. The durable record of verification is `verifiedOn` and',
    '> `verifiedBy` in the data file, never a tick here. See [README.md](README.md).',
    '',
    intro,
    '',
    `Records in this file: **${count}**.`,
    '',
  ].join('\n');
}

function collegeSections(c, programmes, sources) {
  const at = where(sources, `id: '${c.id}'`);
  const parts = [
    `## ${cell(c.dhetName)}`,
    '',
    `### Register record: \`college:${c.id}\``,
    '',
    `Check against DHET's own list. Edit at ${at}.`,
    '',
    HEADER,
    ...provenance(c),
    row("dhetName (as DHET's list prints it)", c.dhetName),
    row('other names DHET prints', (c.otherDhetNames ?? []).join('; ') || NOT_PUBLISHED),
    row('province', c.province),
    row('provinceSourceUrl (opens? gives this province?)', c.provinceSourceUrl ?? NOT_PUBLISHED),
    footer(`college:${c.id}`),
  ];
  if (!c.site) {
    parts.push(
      `No site record: no website of the college's own could be read over HTTPS or trusted, so it has no programmes. Find its official site and research it before any learner sees one.\n`,
    );
    return parts;
  }
  const s = c.site;
  parts.push(
    `### Site record: \`college-site:${c.id}\``,
    '',
    `Check against the college's own website (is it really the college's? its name on the page). Edit at ${at}.`,
    '',
    HEADER,
    ...provenance(s),
    row('name (as the site prints it)', s.name),
    row(
      'abbreviations (only ones the college prints)',
      s.abbreviations.join(', ') || NOT_PUBLISHED,
    ),
    row('website (the official site?)', s.website ?? NOT_PUBLISHED),
    row(
      "domains (every one the college's own? the site links to each as its own?)",
      s.domains.join(', '),
    ),
    row('mainTown (as printed)', s.mainTown ?? NOT_PUBLISHED),
    row('applyUrl (the college’s own application page?)', s.applyUrl ?? NOT_PUBLISHED),
    footer(`college-site:${c.id}`),
    `### Programmes (${programmes.length})`,
    '',
  );
  if (programmes.length === 0) parts.push('None recorded.\n');
  for (const p of programmes) {
    parts.push(
      `#### \`college-programme:${p.id}\``,
      '',
      `${cell(p.nameAtCollege)}. Edit at ${where(sources, `id: '${p.id}'`)}.`,
      '',
      HEADER,
      ...provenance(p),
      row('type', p.type === 'ncv' ? 'NC(V) (after Grade 9)' : 'N4–N6 (after matric or N3)'),
      row('national programme (DHET’s name, or OTHER)', p.programme),
      row('nameAtCollege (as printed)', p.nameAtCollege),
      row('campuses (as printed)', p.campuses ? p.campuses.join(', ') : NOT_PUBLISHED),
      row('yearPrinted', p.yearPrinted ?? NOT_PUBLISHED),
      row('entryQuote (word for word?)', p.entryQuote ?? NOT_PUBLISHED),
      row('entryQuoteUrl (prints the quote?)', p.entryQuoteUrl ?? NOT_PUBLISHED),
      row(
        'entryQuoteIncomplete (code reads no rule from it)',
        p.entryQuoteIncomplete ? 'yes: the page adds conditions the quote doesn’t hold' : 'no',
      ),
      footer(`college-programme:${p.id}`),
    );
  }
  return parts;
}

function noticeSection(n, sources) {
  return [
    `## \`teach-out:${n.id}\``,
    '',
    `${cell(n.circular)}. Edit at ${where(sources, `id: '${n.id}'`)}.`,
    '',
    HEADER,
    ...provenance(n),
    row('circular', n.circular),
    row('title (as printed)', n.title),
    row('datePrinted', n.datePrinted),
    row('type', n.type),
    row('programmes', n.programmes ? n.programmes.join('; ') : 'every programme of the type'),
    row('noFirstIntakeFrom (first year with no first-year intake)', n.noFirstIntakeFrom),
    ...n.quotes.map((q, i) => row(`quote ${i + 1} (word for word?)`, q)),
    row('hostCollegeId (whose copy sourceUrl is)', n.hostCollegeId ?? NOT_PUBLISHED),
    ...n.supportingUrls.map((u, i) => row(`DHET statement ${i + 1} (opens? says the same?)`, u)),
    footer(`teach-out:${n.id}`),
  ].join('\n');
}

/** `{ 'colleges-gauteng.md': markdown, …, 'colleges-teach-outs.md': markdown }`. */
export function collegeChecklists(raw, sources, provinces) {
  const files = {};
  const colleges = raw.colleges ?? [];
  const programmes = raw.collegeProgrammes ?? [];
  for (const province of provinces) {
    const here = colleges.filter((c) => c.province === province);
    if (here.length === 0) continue;
    const count = here.reduce(
      (n, c) => n + 1 + (c.site ? 1 : 0) + programmes.filter((p) => p.collegeId === c.id).length,
      0,
    );
    files[provinceFile(province)] = [
      preamble(
        `Public TVET colleges: ${province}`,
        "Per college: the **register record** against DHET's own list (is it a public college, with this name and province?), the **site record** against the college's own website, then each programme against its page, its entry quote word for word against the page that prints it. Never fill a value the source doesn't print: write \"not published\". Drafts reach no learner until verified (hard rule 3).",
        count,
      ),
      ...here.flatMap((c) =>
        collegeSections(
          c,
          programmes.filter((p) => p.collegeId === c.id),
          sources,
        ),
      ),
    ].join('\n');
  }
  const notices = raw.teachOutNotices ?? [];
  files['colleges-teach-outs.md'] = [
    preamble(
      'TVET teach-outs (DHET circulars)',
      "National circulars that close programmes to first-year students. Plan B leaves a closed programme out even before a person verifies the notice (it only ever closes options). Check each quote word for word against the circular, the date it takes effect, and whether DHET has since published the circular itself on dhet.gov.za (then cite DHET's copy).",
      notices.length,
    ),
    ...notices.map((n) => noticeSection(n, sources)),
  ].join('\n\n');
  return files;
}
