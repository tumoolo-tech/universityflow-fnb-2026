#!/usr/bin/env node
import { readFileSync } from 'node:fs';

/**
 * Conventional Commits check (planning.md §14). A real file rather than an inline `node -e`
 * in lefthook.yml: a YAML folded scalar collapses newlines and corrupts inline scripts.
 */

const TYPES = [
  'feat',
  'fix',
  'docs',
  'style',
  'refactor',
  'perf',
  'test',
  'build',
  'ci',
  'chore',
  'revert',
];

const PATTERN = new RegExp(`^(${TYPES.join('|')})(\\([a-z0-9-]+\\))?!?: .{1,}`);

const messagePath = process.argv[2];
if (!messagePath) {
  console.error('commit-msg: no message file passed');
  process.exit(1);
}

const firstLine = readFileSync(messagePath, 'utf8')
  // Strip a UTF-8 BOM: editors on Windows write one, and it would fail every valid message.
  .replace(/^﻿/, '')
  .split(/\r?\n/)
  .find((line) => line.trim() !== '' && !line.startsWith('#'));

// Merge, revert and fixup commits are generated by git. Leave them alone.
if (!firstLine || /^(Merge|Revert|fixup!|squash!)/.test(firstLine)) {
  process.exit(0);
}

if (!PATTERN.test(firstLine)) {
  console.error('\nCommit message must follow Conventional Commits.\n');
  console.error(`  received: ${firstLine}`);
  console.error('  expected: <type>(<scope>): <subject>');
  console.error(`  types:    ${TYPES.join(', ')}`);
  console.error('\n  e.g. feat(admissions): add the UP score calculator\n');
  process.exit(1);
}
